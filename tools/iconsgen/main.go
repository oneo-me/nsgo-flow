// Command iconsgen writes the Lucide icons NSGo has as the names flow
// files take (flowfile/icons_gen.go) and the app's map from them to
// NSGo's accessors (icons_gen.go). Run it from the repository root with
// go generate after updating NSGo.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/nsgo-dev/nsgo").Output()
	if err != nil {
		log.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), "icons", "lucide", "icons_gen.go"))
	if err != nil {
		log.Fatal(err)
	}
	type icon struct{ fn, name string }
	var icons []icon
	for _, m := range regexp.MustCompile(`(?m)^// (\w+) returns the Lucide ([a-z0-9-]+) icon\.$`).FindAllSubmatch(src, -1) {
		icons = append(icons, icon{string(m[1]), string(m[2])})
	}
	if len(icons) == 0 {
		log.Fatal("no icons found")
	}
	// Sorted, as flowfile looks names up by binary search.
	slices.SortFunc(icons, func(a, b icon) int { return strings.Compare(a.name, b.name) })

	var names, funcs bytes.Buffer
	names.WriteString("// Code generated by tools/iconsgen; DO NOT EDIT.\n\npackage flowfile\n\n" +
		"// lucideNames are the names of every Lucide icon NSGo draws, sorted.\nvar lucideNames = []string{\n")
	funcs.WriteString("// Code generated by tools/iconsgen; DO NOT EDIT.\n\npackage main\n\nimport (\n" +
		"\t\"github.com/nsgo-dev/nsgo/core\"\n\t\"github.com/nsgo-dev/nsgo/icons/lucide\"\n)\n\n" +
		"// lucideIcons are NSGo's Lucide icons by their Lucide names.\nvar lucideIcons = map[string]func() *core.SVG{\n")
	for _, ic := range icons {
		fmt.Fprintf(&names, "\t%q,\n", ic.name)
		fmt.Fprintf(&funcs, "\t%q: lucide.%s,\n", ic.name, ic.fn)
	}
	names.WriteString("}\n")
	funcs.WriteString("}\n")
	write("flowfile/icons_gen.go", names.Bytes())
	write("icons_gen.go", funcs.Bytes())
}

func write(path string, src []byte) {
	src, err := format.Source(src)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
